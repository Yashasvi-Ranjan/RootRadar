/**
 * End-to-end pipeline test with the REAL {@code StatisticalAnomalyDetector}, {@code RuleBasedRootCauseAnalyzer},
 * {@code IncidentServiceImpl}, {@code DetectionPipeline}, graph service and telemetry store on the real PostgreSQL
 * test database. NOTHING is mocked except the wall clock (a controllable test clock) and a spy on the SSE publisher.
 *
 * <p><b>TEST FIXTURE, NOT LIVE DATA.</b> The telemetry windows below are synthetic samples generated by this test
 * (deterministic jitter around fixed means) and written through the normal ingest path into the TEST database
 * ({@code apifd_test}) under service names prefixed {@code t9-}; they are removed after each test. They model the
 * demo scenario: a 2 s slowdown inside payment-service while its "database" dependency stays at ~2 ms.
 */
@SpringBootTest(classes = PaymentSlowdownScenarioIT.TestApp.class)
@ActiveProfiles("test")
class PaymentSlowdownScenarioIT {

    @SpringBootConfiguration
    @EnableAutoConfiguration
    @AutoConfigurationPackage(basePackages = "com.rootradar.apifd")
    @ConfigurationPropertiesScan("com.rootradar.apifd.config")
    @ComponentScan(basePackages = "com.rootradar.apifd", excludeFilters = {
            @ComponentScan.Filter(type = FilterType.CUSTOM, classes = TypeExcludeFilter.class),
            @ComponentScan.Filter(type = FilterType.REGEX,
                    pattern = "com\\.rootradar\\.apifd\\.(Application|testsupport\\..*)")})
    static class TestApp {
        @Bean
        @Primary
        MutableClock testClock() {
            return new MutableClock(Instant.parse("2026-11-16T10:00:00Z"));
        }
    }

    /** Controllable clock: all application code asks this clock for "now". */
    static final class MutableClock extends Clock {
        private volatile Instant now;
        MutableClock(Instant start) { this.now = start; }
        void set(Instant i) { this.now = i; }
        @Override public ZoneId getZone() { return ZoneOffset.UTC; }
        @Override public Clock withZone(ZoneId zone) { return this; }
        @Override public Instant instant() { return now; }
    }

    private static final Instant T0 = Instant.parse("2026-11-16T10:00:00Z");
    private static final String GHOST = "t9-ghost", GW = "t9-gateway", ORD = "t9-order", PAY = "t9-payment", DB = "t9-database";
    private static final int WINDOW = 10;

    @Autowired JdbcTemplate jdbc;
    @Autowired MutableClock clock;
    @Autowired DetectionPipeline pipeline;
    @Autowired IncidentService incidents;
    @Autowired TelemetryIngestService ingest;
    @MockitoSpyBean SseEventPublisher publisher;

    private final Map<String, Long> ids = new java.util.LinkedHashMap<>();
    private boolean ghostDown = false;   // an unrelated, isolated service whose health checks fail
    private int window = 0;   // next window index to be generated

    @BeforeEach
    void fixture() {
        clean();
        for (String n : List.of(GW, ORD, PAY)) {
            ids.put(n, jdbc.queryForObject("""
                    INSERT INTO services (name, display_name, node_type, base_url, health_endpoint, telemetry_endpoint)
                    VALUES (?, ?, 'HTTP_SERVICE', 'http://localhost:9', '/health', '/internal/telemetry') RETURNING id""",
                    Long.class, n, n));
        }
        ids.put(GHOST, jdbc.queryForObject("""
                INSERT INTO services (name, display_name, node_type, base_url, health_endpoint)
                VALUES (?, ?, 'HTTP_SERVICE', 'http://localhost:9', '/health') RETURNING id""", Long.class, GHOST, GHOST));
        ids.put(DB, jdbc.queryForObject("""
                INSERT INTO services (name, display_name, node_type) VALUES (?, ?, 'DEPENDENCY_ONLY') RETURNING id""",
                Long.class, DB, DB));
        edge(GW, ORD, "t9-order-dep");
        edge(ORD, PAY, "t9-payment-dep");
        edge(PAY, DB, "t9-database-dep");
        Mockito.clearInvocations(publisher);
    }

    @AfterEach
    void clean() {
        jdbc.update("DELETE FROM incidents WHERE dedup_key LIKE '%|t9-%'");
        jdbc.update("DELETE FROM anomaly_events WHERE fingerprint LIKE '%|t9-%'");
        jdbc.update("DELETE FROM services WHERE name LIKE 't9-%'");
    }

    private void edge(String from, String to, String measurement) {
        jdbc.update("INSERT INTO service_dependencies (from_service_id, to_service_id, measurement_name) VALUES (?,?,?)",
                ids.get(from), ids.get(to), measurement);
    }

    // ---- synthetic sample generation (TEST FIXTURE) ------------------------------------------------------------

    /** Deterministic jitter in [-1, 1]. */
    private static double jitter(int w, int salt) {
        return Math.sin(w * 1.7 + salt * 0.9);
    }

    /**
     * Generates window {@code w} for all three HTTP services and advances the clock to just after its end.
     * {@code extraPaymentMs} models the injected slowdown inside payment-service (propagates to its callers).
     */
    private void emitWindow(int w, double extraPaymentMs) {
        Instant start = T0.plusSeconds((long) w * WINDOW);
        double dbMs = 2.0 + 0.3 * jitter(w, 1);                      // database stays ~2 ms in every scenario
        double payBase = 20 + 2 * jitter(w, 2);
        double pay = payBase + extraPaymentMs;
        double ord = pay + 15 + 2 * jitter(w, 3);
        double gw = ord + 10 + 2 * jitter(w, 4);
        report(GW, w, start, gw, ORD, "t9-order-dep", ord, "HTTP");
        report(ORD, w, start, ord, PAY, "t9-payment-dep", pay, "HTTP");
        report(PAY, w, start, pay, DB, "t9-database-dep", dbMs, "JDBC");
        clock.set(start.plusSeconds(WINDOW + 2L));
        if (ghostDown) {
            jdbc.update("""
                    INSERT INTO health_check_results (service_id, checked_at, status, outcome, response_time_ms, error_message)
                    VALUES (?, ?, 'DOWN', 'CONNECTION_FAILED', 1, 'Connection refused')""",
                    ids.get(GHOST), java.sql.Timestamp.from(start.plusSeconds(WINDOW)));
        }
        window = w + 1;
    }

    private void report(String service, int w, Instant start, double latencyMs, String dep, String depName,
                        double depMs, String depType) {
        long count = 50 + Math.round(3 * jitter(w, 5));
        double p95 = latencyMs * 1.3;
        TelemetryReport.Overall overall = new TelemetryReport.Overall(count, 0, latencyMs, latencyMs, p95, p95 * 1.1,
                p95 * 1.3);
        TelemetryReport.EndpointStats ep = new TelemetryReport.EndpointStats("POST", "/api/checkout", count, 0,
                latencyMs, latencyMs, p95, p95 * 1.1, p95 * 1.3);
        TelemetryReport.DependencyStats ds = new TelemetryReport.DependencyStats(depName, depType, count, 0, 0, depMs,
                depMs, depMs * 1.3, depMs * 1.4, depMs * 1.6);
        TelemetryReport.Window win = new TelemetryReport.Window(start, start.plusSeconds(WINDOW), overall, List.of(ep),
                List.of(ds));
        ingest.ingest(ids.get(service), new TelemetryReport(1, service, clock.instant(), T0, WINDOW, List.of(win)));
    }

    private int incidentRows() {
        return jdbc.queryForObject("SELECT count(*) FROM incidents WHERE dedup_key LIKE '%|t9-%' OR id IN "
                + "(SELECT incident_id FROM incident_services s JOIN services v ON v.id = s.service_id WHERE v.name LIKE 't9-%')",
                Integer.class);
    }

    private IncidentSummary soleIncident() {
        List<Long> all = jdbc.queryForList("SELECT DISTINCT incident_id FROM incident_services s JOIN services v "
                + "ON v.id = s.service_id WHERE v.name LIKE 't9-%'", Long.class);
        assertEquals(1, all.size(), "exactly one incident expected, got " + all);
        return incidents.findSummary(all.get(0)).orElseThrow();
    }

    // ---- the scenario -------------------------------------------------------------------------------------------

    @Test
    void paymentSlowdownIsDetectedDiagnosedAndRecoveredAsOneIncident() {
        // 1. healthy baseline: 20 windows (200 s), detection runs after each; must stay silent
        for (int w = 0; w < 20; w++) {
            emitWindow(w, 0);
            pipeline.runOnce();
        }
        assertEquals(0, incidentRows(), "no incident (false positive) during a healthy baseline");
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM anomaly_events WHERE fingerprint LIKE '%|t9-%'",
                Integer.class));

        // 2. inject: payment +2000 ms (its callers inherit the latency; database dependency unchanged)
        IncidentSummary inc = null;
        int faultWindows = 0;
        for (; faultWindows < 14; faultWindows++) {
            emitWindow(window, 2000);
            pipeline.runOnce();
            if (faultWindows == 0) {
                assertEquals(0, incidentRows(), "one slow window alone must not open an incident");
            }
            if (incidentRows() > 0) {
                inc = soleIncident();
                if (inc.status() == IncidentStatus.ACTIVE && inc.rootCause() != null) break;
            }
        }
        assertNotNull(inc, "an incident must be created for a sustained 2 s payment slowdown");
        assertEquals(IncidentStatus.ACTIVE, inc.status());
        assertTrue(faultWindows >= 1, "detection needs more than a single sample");

        // 3. diagnosis: payment-service is the probable cause, database is not blamed
        assertEquals(PAY, inc.rootCause().name());
        assertNotNull(inc.rootCauseScore());
        assertTrue(inc.rootCauseScore() > 0 && inc.rootCauseScore() <= 100);
        DiagnosisView diag = incidents.latestDiagnosis(inc.id()).orElseThrow();
        Map<String, ServiceFinding> byService = diag.diagnosis().findings().stream()
                .collect(Collectors.toMap(ServiceFinding::serviceName, f -> f));
        ServiceFinding pay = byService.get(PAY);
        assertNotNull(pay);
        assertEquals(FindingClassification.PROBABLE_CAUSE, pay.classification());
        assertEquals(1, pay.rank());
        assertFalse(pay.factors().isEmpty(), "per-rule score breakdown present");
        assertFalse(pay.evidence().isEmpty(), "evidence sentences present");
        ServiceFinding db = byService.get(DB);
        if (db != null) {
            assertNotEquals(FindingClassification.PROBABLE_CAUSE, db.classification(), "database must not be blamed");
            assertNotEquals(FindingClassification.CONTRIBUTING_FACTOR, db.classification());
            assertTrue(db.score() < pay.score());
        }
        for (String upstream : List.of(ORD, GW)) {
            ServiceFinding f = byService.get(upstream);
            if (f != null) {
                assertNotEquals(FindingClassification.PROBABLE_CAUSE, f.classification(),
                        upstream + " must not be the probable cause");
                assertTrue(f.score() < pay.score());
            }
        }
        assertNotNull(inc.detectedAt());
        assertFalse(inc.impactedServices().isEmpty());

        // 4. fault continues for a while: still exactly one incident (dedup), a single anomaly row per fingerprint
        long id = inc.id();
        for (int i = 0; i < 6; i++) {
            emitWindow(window, 2000);
            pipeline.runOnce();
        }
        assertEquals(1, incidentRows(), "ongoing failure must not create a duplicate incident");
        Integer dupFingerprints = jdbc.queryForObject("""
                SELECT count(*) FROM (SELECT fingerprint FROM anomaly_events WHERE fingerprint LIKE '%|t9-%'
                AND cleared_at IS NULL GROUP BY fingerprint HAVING count(*) > 1) x""", Integer.class);
        assertEquals(0, dupFingerprints, "no duplicate open anomaly rows for one fingerprint");
        assertEquals(id, soleIncident().id());

        // 5. recovery: fault removed; hysteresis => RECOVERING first, RESOLVED only after sustained normal windows
        boolean sawRecovering = false;
        IncidentSummary last = soleIncident();
        for (int i = 0; i < 25 && last.status() != IncidentStatus.RESOLVED; i++) {
            emitWindow(window, 0);
            pipeline.runOnce();
            last = soleIncident();
            if (last.status() == IncidentStatus.RECOVERING) sawRecovering = true;
        }
        assertTrue(sawRecovering, "RECOVERING must precede RESOLVED");
        assertEquals(IncidentStatus.RESOLVED, last.status());
        assertEquals(id, last.id(), "same incident, no duplicate");
        assertNotNull(last.resolvedAt());
        assertEquals(1, incidentRows());

        // 6. history persists: timeline + diagnosis + anomalies retrievable after resolution
        List<TimelineEventType> types = incidents.timeline(id).stream().map(TimelineEntry::eventType).toList();
        assertTrue(types.contains(TimelineEventType.INCIDENT_DETECTED));
        assertTrue(types.contains(TimelineEventType.DIAGNOSIS_UPDATED));
        assertTrue(types.contains(TimelineEventType.RECOVERY_STARTED));
        assertTrue(types.contains(TimelineEventType.RESOLVED));
        assertTrue(types.indexOf(TimelineEventType.RECOVERY_STARTED) < types.indexOf(TimelineEventType.RESOLVED));
        assertFalse(incidents.getDetail(id).anomalies().isEmpty());
        assertTrue(incidents.latestDiagnosis(id).isPresent(), "diagnosis stays accessible after RESOLVED");

        // 7. real-time: lifecycle events were published
        ArgumentCaptor<LiveEvent> cap = ArgumentCaptor.forClass(LiveEvent.class);
        Mockito.verify(publisher, Mockito.atLeastOnce()).publish(cap.capture());
        Set<LiveEventType> published = cap.getAllValues().stream().map(LiveEvent::type).collect(Collectors.toSet());
        assertTrue(published.containsAll(List.of(LiveEventType.INCIDENT_OPENED, LiveEventType.DIAGNOSIS_UPDATED,
                LiveEventType.INCIDENT_RESOLVED, LiveEventType.TELEMETRY_UPDATED)), "published: " + published);
    }

    /**
     * Regression (found in the live QA run): an unrelated service that is DOWN has its own incident. It must neither be
     * pulled into the payment incident's diagnosis/impacted set, nor must the payment/database failure be absorbed into
     * the unrelated incident.
     */
    @Test
    void unrelatedDownServiceDoesNotContaminateThePaymentIncident() {
        ghostDown = true;
        for (int w = 0; w < 20; w++) {
            emitWindow(w, 0);
            pipeline.runOnce();
        }
        List<Long> ghostIncidents = jdbc.queryForList("SELECT incident_id FROM incident_services WHERE service_id = ?",
                Long.class, ids.get(GHOST));
        assertEquals(1, ghostIncidents.size(), "the DOWN service has exactly one incident of its own");
        long ghostIncident = ghostIncidents.get(0);

        for (int w = 0; w < 14; w++) {
            emitWindow(window, 2000);
            pipeline.runOnce();
        }
        Set<String> ghostMembers = incidents.findSummary(ghostIncident).orElseThrow().impactedServices().stream()
                .map(com.rootradar.apifd.common.ServiceRef::name).collect(Collectors.toSet());
        assertEquals(Set.of(GHOST), ghostMembers, "unrelated incident must not grow to the payment chain");

        List<Long> payIncidents = jdbc.queryForList("SELECT DISTINCT incident_id FROM incident_services WHERE service_id = ?",
                Long.class, ids.get(PAY));
        assertEquals(1, payIncidents.size());
        IncidentSummary pay = incidents.findSummary(payIncidents.get(0)).orElseThrow();
        assertEquals(PAY, pay.rootCause().name());
        assertFalse(pay.impactedServices().stream().anyMatch(r -> r.name().equals(GHOST)),
                "unrelated DOWN service is not part of the payment incident");
        assertFalse(incidents.latestDiagnosis(pay.id()).orElseThrow().diagnosis().findings().stream()
                .anyMatch(f -> f.serviceName().equals(GHOST)), "unrelated service is not scored in this diagnosis");
    }
}
